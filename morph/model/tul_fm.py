"""FM1 — the TUL-FM training arm: a flow-matching planner inside the live model.

Arc: ``.agents/notes/proposed/architecture/2026-08-28-tul-fm-arc.md``.
Config: ``morph/configs/tul_fm1.yaml``. Model wiring: ``MORPHTransformer._tul_fm_core``.

WHAT FM1 IS. Skeleton ``tul_a1`` — slots in the sequence, ``prefix_k`` coda positions per
slot, ``E_slot`` / ``W_prefix``, token-state dropout — but with ``n_core: 0``. The core
loop is GONE, and the :class:`~morph.model.fm_planner.FMPlanner` produces the slot states
instead. The slot state of slot ``i`` is a PLAN for span ``i+1``, generated by integrating
a conditional-flow-matching velocity field conditioned on the prelude states at positions
``<= e_i``.

THE ONE NON-NEGOTIABLE. The plan is ``detach()``ed before it is projected into the coda's
prefix positions. No gradient flows from the coda's cross-entropy into the planner, and
none flows through the Euler ladder into the backbone. That detach is the whole reason
this arm cannot develop the takeover disease: there is no BPTT through an iterated map,
because the iterated map is not in the CE graph at all. ``W_prefix`` still trains — it is
downstream of the detach — so the coda can learn to read the plan. See
``tests/test_tul_fm1.py::test_coda_ce_never_reaches_the_planner``.

THE THREE LOSS TERMS, and which parameters each one moves:

| term | gradient reaches |
|---|---|
| ``ce``     | backbone (prelude, coda, embeddings), ``E_slot``, ``E_mask``, ``W_prefix`` |
| ``fm``     | the FMPlanner ONLY — its context input is detached and its target is detached |
| ``sigreg`` | the backbone, through the pooled targets. This is the term that SHAPES them |

The split is deliberate and is the JEPA lesson: if the FM term could move the targets it
would take the cheapest available route and make them predictable rather than
informative. The targets are shaped by CE (they are prelude states of a language model)
and by SIGReg (isotropy), never by being easy to guess.
"""

